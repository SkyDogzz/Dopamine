def rounded_rect(pen, x: int, y: int, width: int, height: int, radius: int) -> None:
	r = min(radius, width // 2, height // 2)
	k = round(r * 0.55228475)
	pen.moveTo((x + r, y))
	pen.lineTo((x + width - r, y))
	pen.curveTo(x + width - r + k, y, x + width, y + r - k, x + width, y + r)
	pen.lineTo((x + width, y + height - r))
	pen.curveTo(x + width, y + height - r + k, x + width - r + k, y + height, x + width - r, y + height)
	pen.lineTo((x + r, y + height))
	pen.curveTo(x + r - k, y + height, x, y + height - r + k, x, y + height - r)
	pen.lineTo((x, y + r))
	pen.curveTo(x, y + r - k, x + r - k, y, x + r, y)
	pen.closePath()


def glyph_grid(char: str, body: bool) -> list[str]:
	if char == " ":
		return []
	if char in ACCENTS:
		base, accent = ACCENTS[char]
		if base.isalpha():
			base_rows = LOWER[base] if body and base.islower() else UPPER[base.upper()]
		else:
			base_rows = DIGITS[base] if base in DIGITS else SYMBOLS[base]
		if char in {"ç", "Ç"}:
			return base_rows[:6] + [base_rows[6], "00010"]
		return accent + base_rows
	if char.islower() and body:
		return LOWER.get(char, UPPER[char.upper()])
	if char.isalpha():
		return UPPER[char.upper()]
	return DIGITS.get(char, SYMBOLS.get(char, ["11111", "10001", "10101", "10101", "10101", "10001", "11111"]))


def add_glyph(font, char: str, body: bool) -> None:
	code = ord(char)
	glyph = font.createChar(code)
	glyph.glyphname = fontforge.nameFromUnicode(code)
	if char == " ":
		glyph.width = 360 if body else 420
		return
	rows = glyph_grid(char, body)
	cell_w, cell_h = (106, 78) if body else (112, 92)
	step_x = 120
	step_y = (88 if len(rows) > 7 else 106) if body else (94 if len(rows) > 7 else 112)
	left, top = (75, 878 if len(rows) > 7 else 820)
	pen = glyph.glyphPen()
	radius = 20 if body else 0
	for row, bits in enumerate(rows[:9]):
		for col, pixel in enumerate(bits):
			if pixel == "1":
				x = left + col * step_x
				y = top - row * step_y - cell_h
				rounded_rect(pen, x, y, cell_w, cell_h, radius)
	glyph.width = 760 if body else 790
	glyph.left_side_bearing = 20


def build_font(family: str, body: bool, path: Path) -> None:
	font = fontforge.font()
	font.encoding = "UnicodeFull"
	font.fontname = family.replace(" ", "") + "Regular"
	font.familyname = family
	font.fullname = family + " Regular"
	font.weight = "Regular"
	font.copyright = "Original glyph designs generated by the Dopamine project; no third-party font outlines used."
	font.version = "1.0"
	font.em = 1000
	chars = set(" " + "".join(UPPER) + "".join(DIGITS) + "".join(LOWER) + "".join(SYMBOLS) + "".join(ACCENTS))
	for char in sorted(chars, key=ord):
		add_glyph(font, char, body)
	font.ascent = 900
	font.descent = 100
	font.hhea_ascent = 900
	font.hhea_descent = -100
	font.hhea_ascent_add = False
	font.hhea_descent_add = False
	font.os2_typoascent = 900
	font.os2_typodescent = -100
	font.os2_typolinegap = 0
	font.os2_typoascent_add = False
	font.os2_typodescent_add = False
	font.os2_winascent = 900
	font.os2_windescent = 100
	font.os2_winascent_add = False
	font.os2_windescent_add = False
	font.os2_use_typo_metrics = True
	path.parent.mkdir(parents=True, exist_ok=True)
	font.generate(str(FONT_OUT / (family.replace(" ", "") + ".ttf")))
	font.save(str(path))
	font.close()
	print(f"Generated {family}: {len(chars)} authored glyph slots")


def main() -> None:
	FONT_OUT.mkdir(parents=True, exist_ok=True)
	build_font("Neon Arcade Pixel", False, SOURCE_OUT / "NeonArcadePixel.sfd")
	build_font("Neon Arcade UI", True, SOURCE_OUT / "NeonArcadeUI.sfd")


if __name__ == "__main__":
	main()
